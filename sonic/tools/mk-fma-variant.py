#!/usr/bin/env python3
"""Generate bench/nbody/config-sonic-fma.sps from config-sonic.sps.

The two variants must differ in NOTHING but the policy wrapper, or the
measurement stops being about contraction. So the contracted one is generated
rather than maintained: run this after any edit to config-sonic.sps.

    python3 sonic/tools/mk-fma-variant.py
"""
import re, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'bench', 'nbody', 'config-sonic.sps')
DST = os.path.join(ROOT, 'bench', 'nbody', 'config-sonic-fma.sps')

# The floating-point kernels. `put!`, `init!` and `main` are startup and are
# left strict, so the generated file differs from the original only where the
# per-step arithmetic lives.
KERNELS = ['advance!', 'kinetic', 'pair-potential', 'subtract-pairs',
           'energy-from', 'offset-momentum!']

HEADER = '''#!r6rs
;;; nbody, SonicScheme configuration WITH D24 CONTRACTION GRANTED.
;;;
;;; GENERATED by sonic/tools/mk-fma-variant.py from config-sonic.sps. Do not
;;; edit: the two variants must differ in nothing but the policy wrapper, or
;;; the measurement stops being about contraction.
;;;
;;; The floating-point kernels wrap their bodies in
;;; `(policy ([fp-contract #f]) ...)`, which is D24's named permission to fuse
;;; a multiply-add. It is a SEPARATE variant, and that is the point of the
;;; permission being named:
;;;
;;;   - config-sonic.sps stays strict, so it stays BIT-EXACT against Chez
;;;     running the same source. That oracle is the strongest single piece of
;;;     evidence this compiler has and nothing may weaken it.
;;;
;;;   - this one cannot be, and is not meant to be. A fused multiply-add rounds
;;;     ONCE where two instructions round twice, so the answer differs in the
;;;     last bits. That is what was asked for, not a bug.
;;;
;;; WHY IT IS THE FAIR COMPARISON. gcc contracts BY DEFAULT --
;;; `-ffp-contract=fast` at every optimisation level -- so `ref.c` under
;;; `-O3 -march=native` has been emitting `vfmadd` all along. Measuring our
;;; twice-rounded arithmetic against its once-rounded arithmetic compared two
;;; different computations, one of which is allowed to use fewer instructions.
'''

def wrap(name, text):
    m = re.search(r'^\(define \(%s([^\n]*)\n' % re.escape(name), text, re.M)
    if not m:
        sys.exit('mk-fma-variant: no kernel named %s' % name)
    start, i, depth = m.start(), m.start(), 0
    while True:
        ch = text[i]
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
            if depth == 0:
                break
        elif ch == ';':
            while text[i] != '\n':
                i += 1
        i += 1
    d = text[start:i + 1]
    head_end = d.index('\n') + 1
    inner = d[head_end:].rstrip()
    assert inner.endswith(')')
    return (text[:start] + d[:head_end] + '  (policy ([fp-contract #f])\n'
            + inner[:-1] + '))' + text[i + 1:])

body = open(SRC).read().split('\n', 1)[1]
for k in KERNELS:
    body = wrap(k, body)
open(DST, 'w').write(HEADER + body)
print('wrote %s' % DST)
